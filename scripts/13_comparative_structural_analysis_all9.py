def json_safe(value):

    if isinstance(value, np.generic):
        return value.item()

    if isinstance(value, Path):
        return str(value)

    if isinstance(value, dict):

        return {
            str(key): json_safe(val)
            for key, val in value.items()
        }

    if isinstance(value, list):

        return [
            json_safe(item)
            for item in value
        ]

    if isinstance(value, tuple):

        return [
            json_safe(item)
            for item in value
        ]

    return value


def write_json(path, data):

    with open(
        path,
        "w",
        encoding="utf-8"
    ) as handle:

        json.dump(
            json_safe(data),
            handle,
            indent=4
        )


