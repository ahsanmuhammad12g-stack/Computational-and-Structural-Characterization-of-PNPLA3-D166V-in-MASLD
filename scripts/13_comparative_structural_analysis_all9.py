def safe_seq1(resname):

    resname = str(
        resname
    ).upper().strip()

    if resname in AA3_TO_AA1:
        return AA3_TO_AA1[resname]

    try:

        return seq1(
            resname
        )

    except Exception:

        return "X"


def residue_number(residue):

    return int(
        residue.id[1]
    )


def get_structure_residue(chain, position):

    for residue in chain:

        try:

            number = residue_number(
                residue
            )

        except Exception:

            continue

        if number == position:

            return residue

    return None


def get_protein_residues(chain):

    return [
        residue
        for residue in chain
        if is_aa(
            residue,
            standard=False
        )
    ]


def get_chain(structure, preferred_chain="A"):

    model = next(
        structure.get_models()
    )

    if preferred_chain in model.child_dict:

        return model[
            preferred_chain
        ]

    chains = list(
        model.get_chains()
    )

    if not chains:

        return None

    return chains[0]


def load_structure(path, structure_id):

    parser = PDBParser(
        QUIET=True
    )

    return parser.get_structure(
        structure_id,
        str(path)
    )


def minimum_heavy_atom_distance(
    residue_a,
    residue_b
):

    atoms_a = [
        atom
        for atom in residue_a
        if str(atom.element).upper() != "H"
    ]

    atoms_b = [
        atom
        for atom in residue_b
        if str(atom.element).upper() != "H"
    ]

    if not atoms_a or not atoms_b:

        return np.nan

    minimum = np.inf

    for atom_a in atoms_a:

        for atom_b in atoms_b:

            distance = np.linalg.norm(
                atom_a.coord
                - atom_b.coord
            )

            if distance < minimum:

                minimum = distance

    return float(minimum)


def get_residue_plddt(residue):

    values = []

    for atom in residue:

        try:

            value = float(
                atom.bfactor
            )

            if value >= 0:

                values.append(
                    value
                )

        except Exception:

            continue

    if not values:

        return np.nan

    return float(
        np.mean(values)
    )


def get_mean_plddt(chain):

    values = []

    for residue in get_protein_residues(
        chain
    ):

        value = get_residue_plddt(
            residue
        )

        if not np.isnan(value):

            values.append(
                value
            )

    if not values:

        return np.nan

    return float(
        np.mean(values)
    )


