def get_backbone_atoms_by_key(
    chain
):

    output = {}

    for residue in get_protein_residues(
        chain
    ):

        position = residue_number(
            residue
        )

        for atom_name in [
            "N",
            "CA",
            "C",
        ]:

            if atom_name in residue:

                output[
                    (
                        position,
                        atom_name
                    )
                ] = residue[
                    atom_name
                ]

    return output


def calculate_rmsd(
    fixed_atoms,
    moving_atoms
):

    if len(fixed_atoms) != len(
        moving_atoms
    ):

        return np.nan

    if len(fixed_atoms) < 1:

        return np.nan

    superimposer = Superimposer()

    superimposer.set_atoms(
        fixed_atoms,
        moving_atoms
    )

    return float(
        superimposer.rms
    )


def parse_catalytic_position(
    value
):

    if pd.isna(value):

        return np.nan

    text = str(
        value
    )

    matches = re.findall(
        r"\b([0-9]{1,4})\b",
        text
    )

    if not matches:

        return np.nan

    return int(
        matches[0]
    )


