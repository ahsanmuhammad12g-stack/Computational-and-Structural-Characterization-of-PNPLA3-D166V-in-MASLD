def structural_impact_index(
    polar_contact_loss,
    lost_contacts,
    gained_contacts,
    catalytic_distance_change,
    local_ca_rmsd,
    physchem_score
):

    polar_component = min(
        max(
            polar_contact_loss,
            0
        ) * 2.0,
        10.0
    )

    lost_component = min(
        max(
            lost_contacts,
            0
        ) * 2.0,
        10.0
    )

    gained_component = min(
        max(
            gained_contacts,
            0
        ) * 1.0,
        5.0
    )

    catalytic_component = min(
        abs(
            catalytic_distance_change
        )
        if not np.isnan(
            catalytic_distance_change
        )
        else 0.0,
        5.0
    )

    local_rmsd_component = min(
        max(
            local_ca_rmsd,
            0
        )
        if not np.isnan(
            local_ca_rmsd
        )
        else 0.0,
        1.0
    ) * 5.0

    total = (
        polar_component
        + lost_component
        + gained_component
        + catalytic_component
        + local_rmsd_component
        + physchem_score
    )

    return {

        "Polar_Contact_Loss_Component":
            polar_component,

        "Lost_Contact_Component":
            lost_component,

        "Gained_Contact_Component":
            gained_component,

        "Catalytic_Distance_Component":
            catalytic_component,

        "Local_RMSD_Component":
            local_rmsd_component,

        "Physicochemical_Component":
            physchem_score,

        "Structural_Impact_Index":
            total,
    }


